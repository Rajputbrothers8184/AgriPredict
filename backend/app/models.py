class CropCycle(Base):
    __tablename__ = "crop_cycles"
    __table_args__ = (
        CheckConstraint("season IN ('rabi', 'kharif', 'yearly')", name="ck_crop_cycles_season"),
        CheckConstraint(
            "status IN ('planned', 'active', 'harvested', 'failed')", name="ck_crop_cycles_status"
        ),
        CheckConstraint("area_acres > 0", name="ck_crop_cycles_area"),
        CheckConstraint(
            "actual_harvest_date IS NULL OR actual_harvest_date >= sowing_date",
            name="ck_crop_cycles_harvest_order",
        ),
        CheckConstraint(
            "expected_yield_kg IS NULL OR expected_yield_kg >= 0", name="ck_crop_cycles_yield"
        ),
        Index("idx_crop_cycles_farm_status", "farm_id", "status"),
        Index("idx_crop_cycles_commodity", "commodity_id"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    farm_id: Mapped[int] = mapped_column(
        ForeignKey("farms.id", ondelete="CASCADE"), nullable=False
    )
    commodity_id: Mapped[int] = mapped_column(
        ForeignKey("commodities.id", ondelete="RESTRICT"), nullable=False
    )
    season: Mapped[str] = mapped_column(String(10), nullable=False, default="yearly")
    area_acres: Mapped[Decimal] = mapped_column(Numeric(10, 2), nullable=False)
    sowing_date: Mapped[date] = mapped_column(Date, nullable=False)
    expected_harvest_date: Mapped[date | None] = mapped_column(Date)
    actual_harvest_date: Mapped[date | None] = mapped_column(Date)
    status: Mapped[str] = mapped_column(String(12), nullable=False, default="active")
    expected_yield_kg: Mapped[Decimal | None] = mapped_column(Numeric(12, 2))
    actual_yield_kg: Mapped[Decimal | None] = mapped_column(Numeric(12, 2))
    notes: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        onupdate=utcnow,
        server_default=func.now(),
    )

    farm: Mapped[Farm] = relationship(back_populates="crop_cycles")
    commodity: Mapped[Commodity] = relationship()
    expenses: Mapped[list[Expense]] = relationship(
        back_populates="crop_cycle", cascade="all, delete-orphan", passive_deletes=True
    )
    sales: Mapped[list[Sale]] = relationship(
        back_populates="crop_cycle", cascade="all, delete-orphan", passive_deletes=True
    )


