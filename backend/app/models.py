"""ORM models — mirror of ``database/schema/001_schema.sql``.

The canonical definition of the data model lives in the SQL file under
``database/``; this module must stay in sync with it, and
``database/tests/test_schema_parity.py`` fails the build if it drifts.

Portability notes
-----------------
* ``Numeric`` is used for all money so SQLite and PostgreSQL agree semantically;
  the service layer converts to ``Decimal`` for arithmetic.
* Enumerations are plain strings with ``CheckConstraint`` rather than native
  ``Enum`` types, matching the SQL and keeping migrations trivial.
* ``DateTime(timezone=True)`` maps to ``TIMESTAMPTZ`` on PostgreSQL. SQLite has
  no timezone type, so values are stored as UTC and normalised on write.
"""

from __future__ import annotations

from datetime import date, datetime, timezone
from decimal import Decimal

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


def utcnow() -> datetime:
    """Timezone-aware UTC now (SQLite stores naive UTC; PostgreSQL keeps tz)."""
    return datetime.now(timezone.utc)


class Base(DeclarativeBase):
    """Declarative base with a shared naming convention for constraints.

    Stable constraint names matter for Alembic: without them, autogenerated
    migration names are random and diffs become unreadable.
    """

    pass


# ---------------------------------------------------------------------------
# users
# ---------------------------------------------------------------------------
class User(Base):
    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint("preferred_language IN ('en', 'ur')", name="ck_users_language"),
        CheckConstraint("theme IN ('light', 'dark', 'system')", name="ck_users_theme"),
        CheckConstraint("role IN ('farmer', 'admin')", name="ck_users_role"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    email: Mapped[str] = mapped_column(String(255), unique=True, nullable=False, index=True)
    full_name: Mapped[str] = mapped_column(String(120), nullable=False)
    phone: Mapped[str | None] = mapped_column(String(32))
    password_hash: Mapped[str] = mapped_column(String(255), nullable=False)
    preferred_language: Mapped[str] = mapped_column(String(5), nullable=False, default="en")
    theme: Mapped[str] = mapped_column(String(10), nullable=False, default="system")
    role: Mapped[str] = mapped_column(String(20), nullable=False, default="farmer")
    token_version: Mapped[int] = mapped_column(Integer, nullable=False, default=1)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        onupdate=utcnow,
        server_default=func.now(),
    )

    farms: Mapped[list[Farm]] = relationship(
        back_populates="user", cascade="all, delete-orphan", passive_deletes=True
    )
    refresh_tokens: Mapped[list[RefreshToken]] = relationship(
        back_populates="user", cascade="all, delete-orphan", passive_deletes=True
    )
    reports: Mapped[list[Report]] = relationship(
        back_populates="user", cascade="all, delete-orphan", passive_deletes=True
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<User id={self.id} email={self.email!r}>"


