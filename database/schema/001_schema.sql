-- ===========================================================================
-- AgriPredict — canonical database schema (version 1)
--
-- Target engine : PostgreSQL 14+
-- Local engine  : SQLite is created from the backend ORM, not from this file
--                 (see database/README.md, "Applying the schema").
--
-- Conventions
--   * money ............ NUMERIC(12,2), PKR
--   * prices ........... PKR per 40 kg (maund) — recorded in column comments
--   * quantities ....... kilograms
--   * timestamps ....... TIMESTAMPTZ, application maintains updated_at
--   * enums ............ VARCHAR + CHECK (portable, easy to extend)
--
-- Apply with:  psql -d agripredict -v ON_ERROR_STOP=1 -f 001_schema.sql
-- ===========================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- users — application accounts
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(255) NOT NULL UNIQUE,
    full_name           VARCHAR(120) NOT NULL,
    phone               VARCHAR(32),
    password_hash       VARCHAR(255) NOT NULL,
    preferred_language  VARCHAR(5)   NOT NULL DEFAULT 'en',
    theme               VARCHAR(10)  NOT NULL DEFAULT 'system',
    role                VARCHAR(20)  NOT NULL DEFAULT 'farmer',
    token_version       INTEGER      NOT NULL DEFAULT 1,
    is_active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_users_language CHECK (preferred_language IN ('en', 'ur')),
    CONSTRAINT ck_users_theme    CHECK (theme IN ('light', 'dark', 'system')),
    CONSTRAINT ck_users_role     CHECK (role IN ('farmer', 'admin'))
);

COMMENT ON TABLE  users IS 'Farmer accounts. Password stored only as a bcrypt hash.';
COMMENT ON COLUMN users.email IS 'Lower-cased before storage; uniqueness is case-insensitive.';
COMMENT ON COLUMN users.token_version IS 'Incremented to invalidate every issued JWT.';

-- ---------------------------------------------------------------------------
-- farms — a physical farm owned by a user
-- ---------------------------------------------------------------------------
CREATE TABLE farms (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            INTEGER      NOT NULL,
    name               VARCHAR(120) NOT NULL,
    district           VARCHAR(80)  NOT NULL,
    tehsil             VARCHAR(80),
    latitude           NUMERIC(9, 6),
    longitude          NUMERIC(9, 6),
    total_area_acres   NUMERIC(10, 2),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_farms_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_farms_latitude  CHECK (latitude  IS NULL OR (latitude  BETWEEN -90  AND 90)),
    CONSTRAINT ck_farms_longitude CHECK (longitude IS NULL OR (longitude BETWEEN -180 AND 180)),
    CONSTRAINT ck_farms_area      CHECK (total_area_acres IS NULL OR total_area_acres >= 0)
);

CREATE INDEX idx_farms_user ON farms (user_id);

COMMENT ON TABLE farms IS 'A farm parcel/unit; coordinates drive weather lookups.';

-- ---------------------------------------------------------------------------
-- commodities — crops that can be planted, priced and forecast
-- ---------------------------------------------------------------------------
CREATE TABLE commodities (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(60)  NOT NULL UNIQUE,
    name_en     VARCHAR(80)  NOT NULL,
    name_ur     VARCHAR(80)  NOT NULL,
    category    VARCHAR(20)  NOT NULL DEFAULT 'other',
    price_unit  VARCHAR(20)  NOT NULL DEFAULT 'PKR/40kg',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_commodities_category CHECK (
        category IN ('cereal', 'vegetable', 'fruit', 'pulse', 'cash_crop', 'other')
    )
);

COMMENT ON TABLE commodities IS 'Reference data seeded from database/seed/001_commodities.sql.';
COMMENT ON COLUMN commodities.price_unit IS 'All prices in this system are PKR per 40 kg (one maund).';

-- ---------------------------------------------------------------------------
-- markets — mandis where prices are quoted and produce is sold
-- ---------------------------------------------------------------------------
CREATE TABLE markets (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(80)  NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL,
    district    VARCHAR(80)  NOT NULL,
    province    VARCHAR(40)  NOT NULL,
    latitude    NUMERIC(9, 6),
    longitude   NUMERIC(9, 6),
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_markets_province CHECK (
        province IN ('Punjab', 'Sindh', 'Khyber Pakhtunkhwa', 'Balochistan',
                     'Gilgit-Baltistan', 'Azad Kashmir', 'Islamabad')
    ),
    CONSTRAINT ck_markets_latitude  CHECK (latitude  IS NULL OR (latitude  BETWEEN -90  AND 90)),
    CONSTRAINT ck_markets_longitude CHECK (longitude IS NULL OR (longitude BETWEEN -180 AND 180))
);

COMMENT ON TABLE markets IS 'Agricultural markets (mandis). Seeded from database/seed/002_markets.sql.';

-- ---------------------------------------------------------------------------
-- crop_cycles — one planting of one commodity on one farm
-- ---------------------------------------------------------------------------
CREATE TABLE crop_cycles (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id                INTEGER      NOT NULL,
    commodity_id           INTEGER      NOT NULL,
    season                 VARCHAR(10)  NOT NULL DEFAULT 'yearly',
    area_acres             NUMERIC(10, 2) NOT NULL,
    sowing_date            DATE         NOT NULL,
    expected_harvest_date  DATE,
    actual_harvest_date    DATE,
    status                 VARCHAR(12)  NOT NULL DEFAULT 'active',
    expected_yield_kg      NUMERIC(12, 2),
    actual_yield_kg        NUMERIC(12, 2),
    notes                  TEXT,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_crop_cycles_farm FOREIGN KEY (farm_id) REFERENCES farms (id) ON DELETE CASCADE,
    CONSTRAINT fk_crop_cycles_commodity FOREIGN KEY (commodity_id) REFERENCES commodities (id) ON DELETE RESTRICT,
    CONSTRAINT ck_crop_cycles_season CHECK (season IN ('rabi', 'kharif', 'yearly')),
    CONSTRAINT ck_crop_cycles_status CHECK (status IN ('planned', 'active', 'harvested', 'failed')),
    CONSTRAINT ck_crop_cycles_area   CHECK (area_acres > 0),
    CONSTRAINT ck_crop_cycles_harvest_order CHECK (
        actual_harvest_date IS NULL OR actual_harvest_date >= sowing_date
    ),
    CONSTRAINT ck_crop_cycles_yield CHECK (
        expected_yield_kg IS NULL OR expected_yield_kg >= 0
    )
);

CREATE INDEX idx_crop_cycles_farm_status ON crop_cycles (farm_id, status);
CREATE INDEX idx_crop_cycles_commodity ON crop_cycles (commodity_id);

COMMENT ON TABLE crop_cycles IS 'A single planting season; parent of expenses and sales.';

-- ---------------------------------------------------------------------------
-- expenses — cost line items against a crop cycle
-- ---------------------------------------------------------------------------
CREATE TABLE expenses (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_cycle_id  INTEGER      NOT NULL,
    category       VARCHAR(20)  NOT NULL,
    amount_pkr     NUMERIC(12, 2) NOT NULL,
    expense_date   DATE         NOT NULL,
    description    VARCHAR(255),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_expenses_cycle FOREIGN KEY (crop_cycle_id) REFERENCES crop_cycles (id) ON DELETE CASCADE,
    CONSTRAINT ck_expenses_category CHECK (category IN (
        'seeds', 'fertilizer', 'pesticide', 'labour', 'irrigation',
        'transport', 'machinery', 'other'
    )),
    CONSTRAINT ck_expenses_amount CHECK (amount_pkr >= 0)
);

CREATE INDEX idx_expenses_cycle_date ON expenses (crop_cycle_id, expense_date);

COMMENT ON COLUMN expenses.amount_pkr IS 'Total amount in PKR for this line item (not a rate).';

-- ---------------------------------------------------------------------------
-- sales — produce sold from a crop cycle
-- ---------------------------------------------------------------------------
CREATE TABLE sales (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_cycle_id     INTEGER      NOT NULL,
    commodity_id      INTEGER      NOT NULL,
    market_id         INTEGER,
    quantity_kg       NUMERIC(12, 2) NOT NULL,
    unit_price_pkr    NUMERIC(12, 2) NOT NULL,
    total_amount_pkr  NUMERIC(14, 2) NOT NULL,
    sale_date         DATE         NOT NULL,
    buyer_name        VARCHAR(120),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_sales_cycle     FOREIGN KEY (crop_cycle_id) REFERENCES crop_cycles (id) ON DELETE CASCADE,
    CONSTRAINT fk_sales_commodity FOREIGN KEY (commodity_id)    REFERENCES commodities (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_market    FOREIGN KEY (market_id)       REFERENCES markets (id)     ON DELETE SET NULL,
    CONSTRAINT ck_sales_quantity CHECK (quantity_kg > 0),
    CONSTRAINT ck_sales_price    CHECK (unit_price_pkr >= 0),
    CONSTRAINT ck_sales_total    CHECK (total_amount_pkr >= 0)
);

CREATE INDEX idx_sales_cycle_date ON sales (crop_cycle_id, sale_date);
CREATE INDEX idx_sales_market     ON sales (market_id);

COMMENT ON COLUMN sales.unit_price_pkr IS 'PKR per 40 kg (maund).';
COMMENT ON COLUMN sales.total_amount_pkr IS 'quantity_kg / 40 * unit_price_pkr, stored for reporting speed.';

-- ---------------------------------------------------------------------------
-- price_records — historical mandi price observations (append-only)
-- ---------------------------------------------------------------------------
CREATE TABLE price_records (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commodity_id   INTEGER      NOT NULL,
    market_id      INTEGER      NOT NULL,
    price_date     DATE         NOT NULL,
    min_price_pkr  NUMERIC(12, 2),
    max_price_pkr  NUMERIC(12, 2),
    avg_price_pkr  NUMERIC(12, 2) NOT NULL,
    source         VARCHAR(30)  NOT NULL DEFAULT 'amis_punjab',
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_price_records_commodity FOREIGN KEY (commodity_id) REFERENCES commodities (id) ON DELETE CASCADE,
    CONSTRAINT fk_price_records_market    FOREIGN KEY (market_id)    REFERENCES markets (id)     ON DELETE CASCADE,
    CONSTRAINT uq_price_records_quote UNIQUE (commodity_id, market_id, price_date),
    CONSTRAINT ck_price_records_avg   CHECK (avg_price_pkr >= 0),
    CONSTRAINT ck_price_records_range CHECK (
        min_price_pkr IS NULL OR max_price_pkr IS NULL OR max_price_pkr >= min_price_pkr
    ),
    CONSTRAINT ck_price_records_source CHECK (
        source IN ('amis_punjab', 'pbs', 'synthetic_fixture', 'manual')
    )
);

CREATE INDEX idx_price_records_commodity_date ON price_records (commodity_id, price_date);
CREATE INDEX idx_price_records_market_date    ON price_records (market_id, price_date);

COMMENT ON TABLE price_records IS 'One quote per commodity/market/day; ingestion is idempotent via uq_price_records_quote.';
COMMENT ON COLUMN price_records.source IS 'synthetic_fixture marks generated test data — never present it as real market data.';

-- ---------------------------------------------------------------------------
-- forecasts — one issued forecast run and its evaluation
-- ---------------------------------------------------------------------------
CREATE TABLE forecasts (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commodity_id  INTEGER      NOT NULL,
    market_id     INTEGER      NOT NULL,
    model_name    VARCHAR(30)  NOT NULL,
    horizon_days  INTEGER      NOT NULL,
    issued_on     DATE         NOT NULL,
    mae           NUMERIC(12, 4),
    rmse          NUMERIC(12, 4),
    metrics_json  TEXT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_forecasts_commodity FOREIGN KEY (commodity_id) REFERENCES commodities (id) ON DELETE CASCADE,
    CONSTRAINT fk_forecasts_market    FOREIGN KEY (market_id)    REFERENCES markets (id)     ON DELETE CASCADE,
    CONSTRAINT ck_forecasts_model CHECK (model_name IN ('seasonal_naive', 'xgboost', 'chronos')),
    CONSTRAINT ck_forecasts_horizon CHECK (horizon_days IN (7, 30)),
    CONSTRAINT ck_forecasts_errors CHECK (
        (mae IS NULL OR mae >= 0) AND (rmse IS NULL OR rmse >= 0)
    )
);

CREATE INDEX idx_forecasts_lookup ON forecasts (commodity_id, market_id, horizon_days, issued_on DESC);

COMMENT ON COLUMN forecasts.mae  IS 'Mean absolute error in PKR/40kg measured on the hold-out window.';
COMMENT ON COLUMN forecasts.rmse IS 'Root mean squared error in PKR/40kg.';
COMMENT ON COLUMN forecasts.metrics_json IS 'JSON text: per-step error, model params, training window.';

-- ---------------------------------------------------------------------------
-- forecast_points — the individual daily predictions
-- ---------------------------------------------------------------------------
CREATE TABLE forecast_points (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forecast_id         INTEGER      NOT NULL,
    target_date         DATE         NOT NULL,
    predicted_price_pkr NUMERIC(12, 2) NOT NULL,
    lower_bound_pkr     NUMERIC(12, 2),
    upper_bound_pkr     NUMERIC(12, 2),
    CONSTRAINT fk_forecast_points_forecast FOREIGN KEY (forecast_id) REFERENCES forecasts (id) ON DELETE CASCADE,
    CONSTRAINT uq_forecast_points_day UNIQUE (forecast_id, target_date),
    CONSTRAINT ck_forecast_points_price CHECK (predicted_price_pkr >= 0)
);

COMMENT ON COLUMN forecast_points.lower_bound_pkr IS 'Approximate 80% interval when the model provides one; NULL for point-only baselines.';

-- ---------------------------------------------------------------------------
-- buyers — cached agricultural buyers from Google Places (or manual entry)
-- ---------------------------------------------------------------------------
CREATE TABLE buyers (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id             VARCHAR(160) NOT NULL UNIQUE,
    name                 VARCHAR(160) NOT NULL,
    category             VARCHAR(24)  NOT NULL DEFAULT 'other',
    address              VARCHAR(255),
    district             VARCHAR(80),
    latitude             NUMERIC(9, 6),
    longitude            NUMERIC(9, 6),
    rating               NUMERIC(2, 1),
    user_ratings_total   INTEGER,
    phone                VARCHAR(40),
    market_id            INTEGER,
    fetched_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_buyers_market FOREIGN KEY (market_id) REFERENCES markets (id) ON DELETE SET NULL,
    CONSTRAINT ck_buyers_category CHECK (category IN (
        'trader', 'commission_agent', 'cold_storage', 'mill', 'cooperative', 'other'
    )),
    CONSTRAINT ck_buyers_rating CHECK (rating IS NULL OR (rating >= 0 AND rating <= 5))
);

CREATE INDEX idx_buyers_district ON buyers (district);

COMMENT ON TABLE buyers IS 'Cached Places results; place_id uniqueness makes refresh an UPSERT.';
COMMENT ON COLUMN buyers.fetched_at IS 'Cache freshness — stale rows are refreshed on demand, not deleted.';

-- ---------------------------------------------------------------------------
-- weather_snapshots — weather observations per farm
-- ---------------------------------------------------------------------------
CREATE TABLE weather_snapshots (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id          INTEGER      NOT NULL,
    observed_at      TIMESTAMPTZ  NOT NULL,
    temperature_c    NUMERIC(5, 2),
    humidity_pct     NUMERIC(5, 2),
    wind_kph         NUMERIC(6, 2),
    precipitation_mm NUMERIC(6, 2),
    condition        VARCHAR(80),
    provider         VARCHAR(20)  NOT NULL DEFAULT 'openweathermap',
    raw_json         TEXT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_weather_farm FOREIGN KEY (farm_id) REFERENCES farms (id) ON DELETE CASCADE,
    CONSTRAINT ck_weather_provider CHECK (provider IN ('openweathermap', 'open-meteo', 'mock')),
    CONSTRAINT ck_weather_humidity CHECK (humidity_pct IS NULL OR (humidity_pct BETWEEN 0 AND 100))
);

CREATE INDEX idx_weather_farm_observed ON weather_snapshots (farm_id, observed_at DESC);

-- ---------------------------------------------------------------------------
-- refresh_tokens — server-side revocation list for JWT refresh
-- ---------------------------------------------------------------------------
CREATE TABLE refresh_tokens (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER      NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL UNIQUE,
    expires_at  TIMESTAMPTZ  NOT NULL,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id, expires_at DESC);

COMMENT ON COLUMN refresh_tokens.token_hash IS 'SHA-256 of the token; the plaintext token is never stored.';

-- ---------------------------------------------------------------------------
-- reports — generated PDF/Excel artefacts (metadata only)
-- ---------------------------------------------------------------------------
CREATE TABLE reports (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER      NOT NULL,
    report_type  VARCHAR(30)  NOT NULL,
    file_format  VARCHAR(5)   NOT NULL,
    filename     VARCHAR(160) NOT NULL,
    size_bytes   INTEGER,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ,
    CONSTRAINT fk_reports_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_reports_type   CHECK (report_type IN ('financial_summary', 'crop_cycle', 'forecast')),
    CONSTRAINT ck_reports_format CHECK (file_format IN ('pdf', 'xlsx')),
    CONSTRAINT ck_reports_size   CHECK (size_bytes IS NULL OR size_bytes >= 0)
);

CREATE INDEX idx_reports_user ON reports (user_id, created_at DESC);

COMMENT ON TABLE reports IS 'Files live outside Git (REPORT_STORAGE_DIR); rows are metadata and expire.';

COMMIT;
