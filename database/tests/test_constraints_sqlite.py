"""Execute the schema on SQLite and prove the integrity rules really fire.

Why SQLite: it needs no server, so these tests run on every contributor's
machine and in CI. The canonical DDL is PostgreSQL-flavoured, so a small dialect
shim translates the handful of PostgreSQL-only constructs. The shim is limited
to syntax — no constraint is removed, so every assertion below is a real test of
the rules defined in ``database/schema/001_schema.sql``.
"""

from __future__ import annotations

import re
import sqlite3
from pathlib import Path

import pytest

SCHEMA_FILE = Path(__file__).resolve().parents[1] / "schema" / "001_schema.sql"


def _to_sqlite(sql: str) -> str:
    """Translate PostgreSQL DDL to SQLite, preserving every constraint."""
    sql = re.sub(r"/\*.*?\*/", "", sql, flags=re.S)
    sql = re.sub(r"^\s*COMMENT ON .*?;\s*$", "", sql, flags=re.S | re.M)
    sql = sql.replace("GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "PRIMARY KEY AUTOINCREMENT")
    sql = sql.replace("TIMESTAMPTZ", "TEXT")
    sql = re.sub(r"\bnow\(\)", "CURRENT_TIMESTAMP", sql)
    sql = sql.replace("NUMERIC", "DECIMAL")
    return sql


def _split_statements(sql: str) -> list[str]:
    """Split on semicolons that are not inside a string literal."""
    statements, buf, in_string = [], [], False
    for char in sql:
        if char == "'":
            in_string = not in_string
        if char == ";" and not in_string:
            statements.append("".join(buf).strip())
            buf = []
        else:
            buf.append(char)
    tail = "".join(buf).strip()
    if tail:
        statements.append(tail)
    return [s for s in statements if s and s.upper() not in {"BEGIN", "COMMIT"}]


@pytest.fixture()
def db() -> sqlite3.Connection:
    conn = sqlite3.connect(":memory:")
    conn.execute("PRAGMA foreign_keys = ON")
    for statement in _split_statements(_to_sqlite(SCHEMA_FILE.read_text(encoding="utf-8"))):
        conn.execute(statement)
    conn.commit()
    yield conn
    conn.close()


def _user(conn: sqlite3.Connection, email: str = "farmer@example.com") -> int:
    cur = conn.execute(
        """INSERT INTO users (email, full_name, password_hash)
           VALUES (?, 'Farmer One', 'hash')""",
        (email,),
    )
    return int(cur.lastrowid)


def _farm(conn: sqlite3.Connection, user_id: int) -> int:
    cur = conn.execute(
        "INSERT INTO farms (user_id, name, district) VALUES (?, 'Main Farm', 'Lahore')",
        (user_id,),
    )
    return int(cur.lastrowid)


def _commodity(conn: sqlite3.Connection, slug: str = "wheat") -> int:
    cur = conn.execute(
        """INSERT INTO commodities (slug, name_en, name_ur)
           VALUES (?, 'Wheat', 'گندم')""",
        (slug,),
    )
    return int(cur.lastrowid)


def _market(conn: sqlite3.Connection, slug: str = "lahore-sabzi-mandi") -> int:
    cur = conn.execute(
        """INSERT INTO markets (slug, name, district, province)
           VALUES (?, 'Lahore Sabzi Mandi', 'Lahore', 'Punjab')""",
        (slug,),
    )
    return int(cur.lastrowid)


def _cycle(conn: sqlite3.Connection, farm_id: int, commodity_id: int) -> int:
    cur = conn.execute(
        """INSERT INTO crop_cycles (farm_id, commodity_id, area_acres, sowing_date)
           VALUES (?, ?, 5.0, '2026-11-01')""",
        (farm_id, commodity_id),
    )
    return int(cur.lastrowid)


