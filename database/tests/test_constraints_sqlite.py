def test_user_email_must_be_unique(db: sqlite3.Connection):
    _user(db, "dup@example.com")
    with pytest.raises(sqlite3.IntegrityError):
        _user(db, "dup@example.com")


def test_price_quote_is_unique_per_commodity_market_day(db: sqlite3.Connection):
    cid, mid = _commodity(db), _market(db)
    insert = (
        "INSERT INTO price_records (commodity_id, market_id, price_date, avg_price_pkr)"
        " VALUES (?, ?, '2026-11-20', 3900)"
    )
    db.execute(insert, (cid, mid))
    # Re-ingesting the same quote must fail loudly rather than double-count.
    with pytest.raises(sqlite3.IntegrityError):
        db.execute(insert, (cid, mid))


def test_forecast_point_is_unique_per_day(db: sqlite3.Connection):
    cid, mid = _commodity(db), _market(db)
    cur = db.execute(
        """INSERT INTO forecasts (commodity_id, market_id, model_name, horizon_days, issued_on)
           VALUES (?, ?, 'seasonal_naive', 7, '2026-11-20')""",
        (cid, mid),
    )
    fid = cur.lastrowid
    point = (
        "INSERT INTO forecast_points (forecast_id, target_date, predicted_price_pkr)"
        " VALUES (?, '2026-11-21', 3925)"
    )
    db.execute(point, (fid,))
    with pytest.raises(sqlite3.IntegrityError):
        db.execute(point, (fid,))


