def test_foreign_key_to_unknown_user_is_rejected(db: sqlite3.Connection):
    with pytest.raises(sqlite3.IntegrityError):
        _farm(db, 9999)


def test_deleting_a_user_cascades_to_farms_cycles_expenses_sales(db: sqlite3.Connection):
    uid = _user(db)
    farm = _farm(db, uid)
    cid = _commodity(db)
    mid = _market(db)
    cycle = _cycle(db, farm, cid)
    db.execute(
        """INSERT INTO expenses (crop_cycle_id, category, amount_pkr, expense_date)
           VALUES (?, 'fertilizer', 12000, '2026-11-06')""",
        (cycle,),
    )
    db.execute(
        """INSERT INTO sales (crop_cycle_id, commodity_id, market_id, quantity_kg,
                              unit_price_pkr, total_amount_pkr, sale_date)
           VALUES (?, ?, ?, 400, 3900, 39000, '2026-11-20')""",
        (cycle, cid, mid),
    )

    db.execute("DELETE FROM users WHERE id = ?", (uid,))

    for table in ("farms", "crop_cycles", "expenses", "sales"):
        remaining = db.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        assert remaining == 0, f"{table} rows survived the user delete"
    # Reference data must survive.
    assert db.execute("SELECT COUNT(*) FROM commodities").fetchone()[0] == 1
    assert db.execute("SELECT COUNT(*) FROM markets").fetchone()[0] == 1


def test_commodity_in_use_cannot_be_deleted(db: sqlite3.Connection):
    cycle = _cycle(db, _farm(db, _user(db)), _commodity(db))
    assert cycle > 0
    with pytest.raises(sqlite3.IntegrityError):
        db.execute("DELETE FROM commodities WHERE id = 1")


def test_market_delete_nulls_the_sale_reference(db: sqlite3.Connection):
    """Delisting a mandi must never delete a farmer's sale record."""
    cid, mid = _commodity(db), _market(db)
    cycle = _cycle(db, _farm(db, _user(db)), cid)
    db.execute(
        """INSERT INTO sales (crop_cycle_id, commodity_id, market_id, quantity_kg,
                              unit_price_pkr, total_amount_pkr, sale_date)
           VALUES (?, ?, ?, 800, 3900, 78000, '2026-11-20')""",
        (cycle, cid, mid),
    )
    db.execute("DELETE FROM markets WHERE id = ?", (mid,))
    row = db.execute("SELECT market_id, total_amount_pkr FROM sales").fetchone()
    assert row is not None, "sale row was deleted with the market"
    assert row[0] is None, "market_id should have been set to NULL"
    assert float(row[1]) == 78000.0


