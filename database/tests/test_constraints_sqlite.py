def test_schema_creates_expected_tables(db: sqlite3.Connection):
    names = {
        r[0]
        for r in db.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
        )
    }
    expected = {
        "users",
        "farms",
        "commodities",
        "markets",
        "crop_cycles",
        "expenses",
        "sales",
        "price_records",
        "forecasts",
        "forecast_points",
        "buyers",
        "weather_snapshots",
        "refresh_tokens",
        "reports",
    }
    assert expected <= names, f"missing tables: {expected - names}"


