"""Static validation of the canonical PostgreSQL schema and seed scripts.

These checks run everywhere (no database server required) and catch the errors
that actually happen in review: a foreign key pointing at a table that was
renamed, a duplicated table, a seed column that no longer exists, an index on a
mistyped column.

They are intentionally parser-light: a tiny statement tokeniser rather than a
PostgreSQL grammar, so they stay fast and dependency-free.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

DATABASE_DIR = Path(__file__).resolve().parents[1]
SCHEMA_FILE = DATABASE_DIR / "schema" / "001_schema.sql"
SEED_FILES = sorted((DATABASE_DIR / "seed").glob("*.sql"))

IDENT = r"[A-Za-z_][A-Za-z0-9_]*"

# Engines/functions that are intentionally PostgreSQL-specific.
ALLOWED_NON_SQLITE = {
    "GENERATED BY DEFAULT AS IDENTITY",
    "TIMESTAMPTZ",
    "now()",
    "COMMENT ON",
}


@pytest.fixture(scope="module")
def schema_sql() -> str:
    assert SCHEMA_FILE.is_file(), f"missing canonical schema: {SCHEMA_FILE}"
    return SCHEMA_FILE.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def seed_sql() -> str:
    assert SEED_FILES, "no seed scripts found"
    return "\n".join(p.read_text(encoding="utf-8") for p in SEED_FILES)


def _strip_comments(sql: str) -> str:
    sql = re.sub(r"/\*.*?\*/", "", sql, flags=re.S)
    sql = re.sub(r"--[^\n]*", "", sql)
    return sql


def _tables(sql: str) -> dict[str, str]:
    """Map table name -> body text of the CREATE TABLE statement."""
    body = _strip_comments(sql)
    tables: dict[str, str] = {}
    for match in re.finditer(
        rf"CREATE\s+TABLE\s+({IDENT})\s*\((.*?)\n\);", body, flags=re.S | re.I
    ):
        tables[match.group(1).lower()] = match.group(2)
    return tables


def _columns_of(table_body: str) -> set[str]:
    """Column names declared directly in a CREATE TABLE body (not constraints)."""
    columns: set[str] = set()
    for raw_line in table_body.splitlines():
        line = raw_line.strip().rstrip(",")
        if not line:
            continue
        upper = line.upper()
        if upper.startswith(
            (
                "CONSTRAINT",
                "PRIMARY KEY",
                "FOREIGN KEY",
                "UNIQUE",
                "CHECK",
                "EXCLUDE",
            )
        ):
            continue
        match = re.match(IDENT, line)
        if match:
            columns.add(match.group(0).lower())
    return columns


def test_schema_file_exists_and_is_transactional(schema_sql: str):
    cleaned = _strip_comments(schema_sql).strip()
    assert cleaned.upper().startswith("BEGIN;"), "schema must open a transaction"
    assert cleaned.upper().endswith("COMMIT;"), "schema must close its transaction"


def test_table_names_are_unique(schema_sql: str):
    names = re.findall(
        rf"CREATE\s+TABLE\s+({IDENT})\s*\(", _strip_comments(schema_sql), flags=re.I
    )
    lowered = [n.lower() for n in names]
    duplicates = {n for n in lowered if lowered.count(n) > 1}
    assert not duplicates, f"duplicate CREATE TABLE for: {sorted(duplicates)}"


def test_all_foreign_keys_target_existing_tables(schema_sql: str):
    tables = _tables(schema_sql)
    assert tables, "no tables parsed from the schema"
    missing = []
    for table, body in tables.items():
        for target in re.findall(r"REFERENCES\s+([A-Za-z_][A-Za-z0-9_]*)", body, flags=re.I):
            if target.lower() not in tables:
                missing.append(f"{table} -> {target}")
    assert not missing, f"foreign keys reference unknown tables: {missing}"


def test_foreign_keys_declare_an_on_delete_action(schema_sql: str):
    """Silent `NO ACTION` defaults are a design smell for owned child rows."""
    tables = _tables(schema_sql)
    offenders = []
    for table, body in tables.items():
        for fk_line in re.findall(
            r"CONSTRAINT\s+\w+\s+FOREIGN KEY[^,]*?REFERENCES[^,]*", body, flags=re.I | re.S
        ):
            if "ON DELETE" not in fk_line.upper():
                offenders.append(f"{table}: {' '.join(fk_line.split())[:90]}")
    assert not offenders, f"foreign keys without ON DELETE: {offenders}"


def test_every_table_has_a_primary_key(schema_sql: str):
    for table, body in _tables(schema_sql).items():
        assert re.search(r"PRIMARY\s+KEY", body, flags=re.I), f"{table} has no primary key"


def test_created_at_columns_are_not_nullable_with_default(schema_sql: str):
    for table, body in _tables(schema_sql).items():
        for line in body.splitlines():
            stripped = line.strip()
            if stripped.lower().startswith("created_at"):
                assert "NOT NULL" in stripped.upper(), f"{table}.created_at must be NOT NULL"
                assert "DEFAULT" in stripped.upper(), f"{table}.created_at must have a default"


def test_indexes_reference_existing_tables_and_columns(schema_sql: str):
    tables = _tables(schema_sql)
    columns = {t: _columns_of(b) for t, b in tables.items()}
    cleaned = _strip_comments(schema_sql)
    problems = []
    for match in re.finditer(
        rf"CREATE\s+INDEX\s+({IDENT})\s+ON\s+({IDENT})\s*\(([^)]*)\)", cleaned, flags=re.I
    ):
        index_name, table, cols = match.group(1), match.group(2).lower(), match.group(3)
        if table not in tables:
            problems.append(f"{index_name}: unknown table {table}")
            continue
        for col in cols.split(","):
            col_name = col.strip().split()[0].lower()
            if col_name and col_name not in columns[table]:
                problems.append(f"{index_name}: {table}.{col_name} does not exist")
    assert not problems, f"invalid indexes: {problems}"


ALLOWED_TYPES = {
    "INTEGER", "VARCHAR", "NUMERIC", "DECIMAL", "DATE", "TIMESTAMPTZ",
    "TIMESTAMP", "BOOLEAN", "TEXT",
}
NON_COLUMN_PREFIXES = (
    "CONSTRAINT", "PRIMARY KEY", "FOREIGN KEY", "UNIQUE", "CHECK", "EXCLUDE",
)


def _split_top_level(body: str) -> list[str]:
    """Split a CREATE TABLE body on commas that are not inside parentheses."""
    parts, buf, depth, in_string = [], [], 0, False
    for char in body:
        if char == "'":
            in_string = not in_string
        if not in_string:
            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
            elif char == "," and depth == 0:
                parts.append("".join(buf).strip())
                buf = []
                continue
        buf.append(char)
    if "".join(buf).strip():
        parts.append("".join(buf).strip())
    return parts


def _column_definitions(sql: str):
    """Yield ``(table, column, type, definition)`` for every real column.

    Parses the CREATE TABLE bodies structurally, so multi-line CHECK clauses,
    COMMENT statements and constraints can never be mistaken for a column.
    """
    for table, body in _tables(sql).items():
        for definition in _split_top_level(body):
            flat = " ".join(definition.split())
            if not flat or flat.upper().startswith(NON_COLUMN_PREFIXES):
                continue
            match = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s+([A-Za-z]+(?:\s+[A-Za-z]+)?)", flat)
            if not match:
                continue
            column = match.group(1).lower()
            sql_type = match.group(2).upper().split()[0]
            if sql_type not in ALLOWED_TYPES:
                continue
            yield table, column, sql_type, flat


# Columns that hold money in PKR, or a price error, and therefore must be NUMERIC.
MONEY_NAME = re.compile(r"(_pkr|_amount|^mae$|^rmse$)")


def test_money_and_price_columns_use_numeric(schema_sql: str):
    """Floating-point money is a defect; NUMERIC/DECIMAL is required."""
    checked, problems = 0, []
    for _table, column, sql_type, line in _column_definitions(schema_sql):
        if not MONEY_NAME.search(column):
            continue
        checked += 1
        if sql_type not in {"NUMERIC", "DECIMAL"}:
            problems.append(f"{column} is {sql_type}: {line}")
    assert checked >= 10, f"expected the money columns to be found, matched only {checked}"
    assert not problems, f"money columns must be NUMERIC: {problems}"


def test_prices_and_amounts_are_never_floats(schema_sql: str):
    for _table, column, sql_type, line in _column_definitions(schema_sql):
        if MONEY_NAME.search(column):
            assert sql_type not in {"REAL", "FLOAT", "DOUBLE", "MONEY"}, (
                f"{column} uses an inexact type: {line}"
            )


# Credentials may only be stored as hashes or counters.
ALLOWED_CREDENTIAL_COLUMNS = {"password_hash", "token_hash", "token_version"}
CREDENTIAL_NAME = re.compile(r"(password|secret|api_key|^token|_token)")


def test_no_plaintext_secret_columns(schema_sql: str):
    offenders = [
        line
        for _table, column, _type, line in _column_definitions(schema_sql)
        if CREDENTIAL_NAME.search(column) and column not in ALLOWED_CREDENTIAL_COLUMNS
    ]
    assert not offenders, f"schema must not store plaintext credentials: {offenders}"


def test_seed_files_are_idempotent(seed_sql: str):
    """Every INSERT must declare a conflict strategy so re-running is safe."""
    cleaned = _strip_comments(seed_sql)
    inserts = re.findall(r"INSERT\s+INTO\s+(\w+)", cleaned, flags=re.I)
    assert inserts, "no INSERT statements found in seed data"
    assert cleaned.upper().count("ON CONFLICT") == len(inserts), (
        "every seed INSERT must have ON CONFLICT to stay idempotent"
    )


def test_seed_columns_exist_in_schema(schema_sql: str, seed_sql: str):
    tables = _tables(schema_sql)
    columns = {t: _columns_of(b) for t, b in tables.items()}
    cleaned = _strip_comments(seed_sql)
    problems = []
    for match in re.finditer(
        rf"INSERT\s+INTO\s+({IDENT})\s*\(([^)]*)\)", cleaned, flags=re.I
    ):
        table, col_list = match.group(1).lower(), match.group(2)
        if table not in tables:
            problems.append(f"seed inserts into unknown table {table}")
            continue
        for col in col_list.split(","):
            col_name = col.strip().lower()
            if col_name not in columns[table]:
                problems.append(f"{table}.{col_name} from seed does not exist in schema")
    assert not problems, f"seed/schema mismatch: {problems}"


def test_seed_references_only_known_enumerations(seed_sql: str):
    """Guards against typos in CHECK-constrained values."""
    cleaned = _strip_comments(seed_sql).lower()
    allowed_categories = {
        "cereal",
        "vegetable",
        "fruit",
        "pulse",
        "cash_crop",
        "other",
        "trader",
        "commission_agent",
        "cold_storage",
        "mill",
        "cooperative",
    }
    found = set(re.findall(r"'([a-z_]+)'", cleaned)) & {
        "cereals",
        "vegetables",
        "fruits",
        "pulses",
        "cash_crops",
        "traders",
    }
    assert not found, f"non-canonical category values in seed data: {found}"
    # Every quoted single-word category we do see must be in the canonical set.
    quoted = set(re.findall(r"'([a-z]+_[a-z]+|[a-z]{3,})'", cleaned))
    suspicious = {
        q
        for q in quoted
        if q.endswith("s") and q[:-1] in allowed_categories and q not in allowed_categories
    }
    assert not suspicious, f"pluralised enumeration values: {suspicious}"


